package io.github.alexmagter.swiftui2composable.processor

import java.io.File

fun generateSwift(
    outDir: File,
    framework: String,
    components: List<Component>
){
    SwiftGenerator(
        outDir = outDir,
        framework = framework,
        components = components
    ).generate()
}

// codeGenerator would send non-kt files to resources/, so the swift file is written by hand
private class SwiftGenerator(
    private val outDir: File,
    private val framework: String,
    private val components: List<Component>
){
    fun generate(){
        val file = File(outDir, FILE_NAME)
        val content = buildFile()

        // same content -> don't touch it, xcode would recompile it
        if (file.exists() && file.readText() == content) return

        outDir.mkdirs()
        file.writeText(content)
    }

    private fun buildFile(): String = buildString {
        append(header())
        append(runtime())
        append(registry())
    }

    private fun header() = """
        |// Generated by SwiftUI2Composable. Do not edit.
        |
        |import SwiftUI
        |import $framework
        |
        |
    """.trimMargin()

    // fixed part: hosts a SwiftUI view and pushes new props into it
    // a new rootView of the same type is diffed by swiftui, so @State and @StateObject survive
    private fun runtime() = """
        |final class SwiftUINativeView<S: AnyObject, V: View>: NSObject, NativeView {
        |    private let hosting: UIHostingController<V>
        |    private let content: (S) -> V
        |
        |    var viewController: UIViewController { hosting }
        |
        |    init(initial: S, content: @escaping (S) -> V) {
        |        let hosting = UIHostingController(rootView: content(initial))
        |        hosting.view.backgroundColor = .clear
        |        self.hosting = hosting
        |        self.content = content
        |        super.init()
        |    }
        |
        |    func update(state: Any) {
        |        hosting.rootView = content(state as! S)
        |    }
        |}
        |
        |
    """.trimMargin()

    private fun registry(): String {
        val methods = components.joinToString("\n\n") { c ->
            """
            |    func create${c.name}(props: ${c.props.simpleName}, callbacks: any ${c.callbacks.simpleName}) -> any NativeView {
            |        SwiftUINativeView(initial: props) { ${c.swiftView}(props: ${'$'}0, callbacks: callbacks) }
            |    }
            """.trimMargin()
        }

        return """
            |final class GeneratedSwiftBridge: NSObject, SwiftBridgeRegistry {
            |$methods
            |}
            |
        """.trimMargin()
    }

    companion object {
        const val FILE_NAME = "SwiftUI2Composable.swift"
    }
}
